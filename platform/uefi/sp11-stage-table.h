/* Chainload stage-candidate table for the Surface Pro 11 (SNAP_PLATFORM_SP11), docs/
 * SP11-Q1N1-BOOT-STUDY.md section 9.1: the A16 build hard-codes three fixed stage addresses
 * (main.c stage_candidates[], 0xb0000000/0x4c000000/0xa0000000) chosen to fit the A16's own
 * memory map; nothing about those addresses may be assumed to fit the Surface Pro 11's, which is
 * UNKNOWN until X2 item 8 measures the real DRAM map. This table, like sp11-usb-ports.h's USB
 * table, is board-descriptor-derived, external build input: unknown values fail closed, and this
 * file supplies no default.
 *
 * ABI shared with a future host tool (mirroring sp11_usb_ports.py's own emit-c convention for the
 * USB table; no such tool exists yet for this table, docs/SP11-Q1N1-BOOT-STUDY.md section 12 item
 * 3 leaves the board-config carrier itself an open question -- see this patch's REPORT.md). Change
 * the magic/version together with any future generator. */
#pragma once
#include <stdint.h>

#ifndef SNAP_PLATFORM_SP11
#define SNAP_PLATFORM_SP11 0
#endif

#if SNAP_PLATFORM_SP11

#define Q1N1_SP11_STAGE_MAGIC UINT64_C(0x3147415453504531) /* "1EPSTAG1", little endian */
#define Q1N1_SP11_STAGE_VERSION 1u
#define Q1N1_SP11_STAGE_MAX_CANDIDATES 4u
/* main.c STAGE_BYTES: every candidate must reserve at least this much, non-overlapping. */
#define Q1N1_SP11_STAGE_BYTES (16u << 20)

struct q1n1_sp11_stage_table {
    uint64_t magic;
    uint32_t version;
    uint32_t count;      /* candidates in use, 1..Q1N1_SP11_STAGE_MAX_CANDIDATES */
    uint64_t candidate[Q1N1_SP11_STAGE_MAX_CANDIDATES]; /* physical base addresses, in try-order */
};
_Static_assert(sizeof(struct q1n1_sp11_stage_table) == 48, "table layout is shared with any future generator");

enum {
    Q1N1_SP11_STAGE_OK = 0,
    Q1N1_SP11_STAGE_ERR_NULL,
    Q1N1_SP11_STAGE_ERR_MAGIC,
    Q1N1_SP11_STAGE_ERR_VERSION,
    Q1N1_SP11_STAGE_ERR_COUNT,
    Q1N1_SP11_STAGE_ERR_RESERVED,
    Q1N1_SP11_STAGE_ERR_ALIGN,     /* a candidate is not page aligned */
    Q1N1_SP11_STAGE_ERR_A16_BASE,  /* a candidate equals one of the A16's own stage addresses */
    Q1N1_SP11_STAGE_ERR_OVERLAP,   /* two candidates, each Q1N1_SP11_STAGE_BYTES wide, overlap */
    Q1N1_SP11_STAGE_ERR_COUNT_ALL
};
const char *q1n1_sp11_stage_error_name(int code);

/* Pure check of a table; no memory outside it is read. Returns Q1N1_SP11_STAGE_OK or the first error. */
int q1n1_sp11_stage_table_validate(const struct q1n1_sp11_stage_table *table);

/* The table in use. A build generated by a future board-config tool defines it next to the data; a
 * host test defines its own. Never defined by q1n1 itself, so a build without a derived table does
 * not link (the same convention sp11-usb-ports.h already uses for q1n1_sp11_usb_table_get). */
const struct q1n1_sp11_stage_table *q1n1_sp11_stage_table_get(void);

#endif /* SNAP_PLATFORM_SP11 */
